package tj.metro.dushanbe.ticketing.web.dto;

/**
 * Результат покупки (U-CIT-08).
 *
 * <p><b>Единственное место, где существует токен QR.</b> Он не сохраняется (в БД
 * лежит только SHA-256) и не возвращается больше нигде. Потерянный токен
 * невосстановим — это цена того, что дамп БД не даёт проехать по чужому билету.
 *
 * <p>Отказ платежа — это тоже нормальный ответ, а не ошибка: {@code ticket} и
 * {@code token} равны null, {@code payment.status = failed}, а причина лежит в
 * {@code payment.failureReason}. Контроллер отдаёт такой ответ с HTTP 402.
 * Исключение вместо ответа откатило бы транзакцию и стёрло запись об
 * отклонённой попытке — ровно ту, что нужна антифроду (TKT-06).
 *
 * @param notice обязательная человекочитаемая пометка demo-контура: пассажир
 *               должен видеть, что платежа не было и билет недействителен для
 *               проезда
 */
public record TicketPurchaseResponse(
        TicketDto ticket,
        String token,
        PaymentDto payment,
        boolean demo,
        String notice) {
}
