-- V026: демо-тарифы больше не активны по умолчанию (аудит §23).
--
-- Почему отдельная миграция, а не правка V018. Демо-тарифы DEMO-SINGLE и
-- DEMO-MONTHLY вставлены прямо в V018 (схема fare_product) с is_active = true,
-- то есть публичный GET /v1/fares отдавал бы выдуманные цены как официальный
-- тариф метро. Вынести INSERT из V018 в db/seed нельзя: это изменит контрольную
-- сумму уже применённой миграции и уронит flyway validate на всех существующих
-- базах. Поэтому V018 остаётся байт-в-байт прежней, а её эффект отменяется
-- отдельной версией.
--
-- Эта миграция лежит в db/migration, то есть применяется ВЕЗДЕ, включая
-- production. В dev/test/демо-контуре следом идёт V027 из db/seed, которая
-- возвращает демо-тарифы в активное состояние — там демонстрировать нечего без них.
--
-- Деактивация, а не DELETE: на fare_product ссылаются билеты и платежи (V023),
-- удаление строк оборвало бы историю. is_active = false достаточно —
-- FareService отдаёт публично только активные продукты.
UPDATE fare_product
   SET is_active = false,
       updated_at = now()
 WHERE code IN ('DEMO-SINGLE', 'DEMO-MONTHLY');
