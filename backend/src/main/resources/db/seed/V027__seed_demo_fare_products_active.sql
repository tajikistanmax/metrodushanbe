-- Каталог db/seed не входит в spring.flyway.locations профиля prod, поэтому в
-- production этой версии просто не существует и демо-тарифы остаются погашенными.
--
-- ВНИМАНИЕ: данные демонстрационные (placeholder), как и сеть из V002.
-- Реальные тарифы утверждаются отдельно и вводятся через admin-консоль.
